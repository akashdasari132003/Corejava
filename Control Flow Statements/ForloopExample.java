package com.version1;

public class ForloopExample {

	public static void main(String[] args) {
		
		for(int i=1;i<=10;i++) {
			System.out.println("Hello "+i);
		}
		System.out.println("=====================================");
		
		
		for(int i = 10;i>=1;i--) {
			System.out.println("Hello "+i);
		}

	}

}
